-- Apply once to existing installations before deploying the reflective engine.
create table if not exists public.trade_reflections (
    reflection_id bigint generated by default as identity primary key,
    trade_id bigint not null unique references public.trades(trade_id) on delete cascade,
    account_id bigint not null references public.trading_accounts(account_id) on delete cascade,
    symbol varchar not null,
    outcome varchar check (outcome in ('win', 'loss', 'breakeven')),
    entry_price numeric not null,
    exit_price numeric not null,
    profit_loss numeric not null,
    holding_seconds bigint not null check (holding_seconds >= 0),
    original_ai_reasoning text not null default '',
    category varchar,
    lesson text,
    status varchar not null default 'processing'
        check (status in ('processing', 'completed', 'failed')),
    error text,
    claimed_at timestamptz not null default now(),
    created_at timestamptz not null default now(),
    reflected_at timestamptz
);

create table if not exists public.learned_rules (
    rule_id bigint generated by default as identity primary key,
    account_id bigint not null references public.trading_accounts(account_id) on delete cascade,
    symbol varchar not null,
    category varchar not null,
    rule_text text not null,
    source_trade_id bigint not null references public.trades(trade_id) on delete cascade,
    confidence numeric not null default 0.5 check (confidence between 0 and 1),
    supporting_trades integer not null default 1 check (supporting_trades > 0),
    active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint learned_rules_account_symbol_category_text_key
        unique (account_id, symbol, category, rule_text)
);

create index if not exists trade_reflections_account_status_idx
    on public.trade_reflections (account_id, status, claimed_at);
create index if not exists learned_rules_account_symbol_active_idx
    on public.learned_rules (
        account_id,
        symbol,
        active,
        supporting_trades desc,
        confidence desc,
        updated_at desc
    );

alter table public.trade_reflections enable row level security;
alter table public.learned_rules enable row level security;

drop policy if exists "Users can read assigned trade reflections"
    on public.trade_reflections;
create policy "Users can read assigned trade reflections"
    on public.trade_reflections for select to authenticated
    using (
        exists (
            select 1
            from public.dashboard_account_access access
            where access.account_id = trade_reflections.account_id
              and access.user_id = (select auth.uid())
        )
    );

drop policy if exists "Users can read assigned learned rules"
    on public.learned_rules;
create policy "Users can read assigned learned rules"
    on public.learned_rules for select to authenticated
    using (
        exists (
            select 1
            from public.dashboard_account_access access
            where access.account_id = learned_rules.account_id
              and access.user_id = (select auth.uid())
        )
    );

grant select on public.trade_reflections to authenticated;
grant select on public.learned_rules to authenticated, service_role;

create or replace function public.claim_trade_reflections(
    p_account_id bigint,
    p_batch_size integer default 5
)
returns table (
    trade_id bigint,
    symbol text,
    action text,
    open_price numeric,
    close_price numeric,
    profit_loss numeric,
    holding_seconds bigint,
    ai_reasoning text
)
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
begin
    if auth.role() is distinct from 'service_role' then
        raise exception 'Only the trading engine may claim reflections.';
    end if;

    return query
    with eligible as materialized (
        select
            trade.trade_id,
            trade.account_id,
            trade.symbol,
            trade.action,
            trade.open_price,
            trade.close_price,
            trade.profit_loss,
            greatest(
                0,
                extract(epoch from (trade.close_time - trade.open_time))::bigint
            ) as holding_seconds,
            coalesce(ai.ai_reasoning, '') as ai_reasoning
        from public.trades trade
        left join public.trade_reflections reflection
            on reflection.trade_id = trade.trade_id
        left join lateral (
            select log.ai_reasoning
            from public.ai_trade_logs log
            where log.trade_id = trade.trade_id
            order by log.created_at desc, log.log_id desc
            limit 1
        ) ai on true
        where trade.account_id = p_account_id
          and trade.status = 'closed'
          and trade.close_price is not null
          and trade.close_time is not null
          and trade.profit_loss is not null
          and (
              reflection.trade_id is null
              or reflection.status = 'failed'
              or (
                  reflection.status = 'processing'
                  and reflection.claimed_at < now() - interval '15 minutes'
              )
          )
        order by trade.close_time, trade.trade_id
        limit greatest(1, least(coalesce(p_batch_size, 5), 100))
        for update of trade skip locked
    ),
    claimed as (
        insert into public.trade_reflections (
            trade_id,
            account_id,
            symbol,
            entry_price,
            exit_price,
            profit_loss,
            holding_seconds,
            original_ai_reasoning,
            status,
            claimed_at,
            error
        )
        select
            eligible.trade_id,
            eligible.account_id,
            eligible.symbol,
            eligible.open_price,
            eligible.close_price,
            eligible.profit_loss,
            eligible.holding_seconds,
            eligible.ai_reasoning,
            'processing',
            now(),
            null
        from eligible
        on conflict (trade_id) do update
        set account_id = excluded.account_id,
            symbol = excluded.symbol,
            entry_price = excluded.entry_price,
            exit_price = excluded.exit_price,
            profit_loss = excluded.profit_loss,
            holding_seconds = excluded.holding_seconds,
            original_ai_reasoning = excluded.original_ai_reasoning,
            status = 'processing',
            claimed_at = now(),
            error = null
        where trade_reflections.status = 'failed'
           or (
               trade_reflections.status = 'processing'
               and trade_reflections.claimed_at < now() - interval '15 minutes'
           )
        returning trade_reflections.trade_id
    )
    select
        eligible.trade_id,
        eligible.symbol::text,
        eligible.action::text,
        eligible.open_price,
        eligible.close_price,
        eligible.profit_loss,
        eligible.holding_seconds,
        eligible.ai_reasoning::text
    from eligible
    join claimed on claimed.trade_id = eligible.trade_id;
end;
$$;

create or replace function public.complete_trade_reflection(
    p_trade_id bigint,
    p_outcome text,
    p_category text,
    p_lesson text,
    p_original_ai_reasoning text
)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
    reflection_account_id bigint;
    reflection_symbol text;
    reflection_pnl numeric;
    expected_outcome text;
begin
    if auth.role() is distinct from 'service_role' then
        raise exception 'Only the trading engine may complete reflections.';
    end if;
    if p_outcome not in ('win', 'loss', 'breakeven')
       or length(trim(coalesce(p_category, ''))) not between 1 and 80
       or length(trim(coalesce(p_lesson, ''))) not between 1 and 500 then
        raise exception 'Invalid reflection result.';
    end if;

    select account_id, symbol, profit_loss
    into reflection_account_id, reflection_symbol, reflection_pnl
    from public.trade_reflections
    where trade_id = p_trade_id and status = 'processing'
    for update;
    if not found then
        raise exception 'Trade reflection % is not currently claimed.', p_trade_id;
    end if;

    expected_outcome := case
        when reflection_pnl < 0 then 'loss'
        when reflection_pnl > 0 then 'win'
        else 'breakeven'
    end;
    if p_outcome <> expected_outcome then
        raise exception 'Reflection outcome does not match trade PnL.';
    end if;

    update public.trade_reflections
    set outcome = p_outcome,
        category = trim(p_category),
        lesson = trim(p_lesson),
        original_ai_reasoning = coalesce(p_original_ai_reasoning, ''),
        status = 'completed',
        error = null,
        reflected_at = now()
    where trade_id = p_trade_id;

    insert into public.learned_rules (
        account_id,
        symbol,
        category,
        rule_text,
        source_trade_id
    )
    values (
        reflection_account_id,
        reflection_symbol,
        trim(p_category),
        trim(p_lesson),
        p_trade_id
    )
    on conflict (account_id, symbol, category, rule_text) do update
    set supporting_trades = learned_rules.supporting_trades + 1,
        source_trade_id = excluded.source_trade_id,
        updated_at = now();
end;
$$;

create or replace function public.fail_trade_reflection(
    p_trade_id bigint,
    p_error text
)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
begin
    if auth.role() is distinct from 'service_role' then
        raise exception 'Only the trading engine may update reflection status.';
    end if;

    update public.trade_reflections
    set status = 'failed',
        error = left(coalesce(p_error, 'Unknown reflection error'), 2000),
        claimed_at = now()
    where trade_id = p_trade_id and status = 'processing';
    if not found then
        raise exception 'Trade reflection % is not currently claimed.', p_trade_id;
    end if;
end;
$$;

revoke all on function public.claim_trade_reflections(bigint, integer)
    from public, anon, authenticated;
revoke all on function public.complete_trade_reflection(bigint, text, text, text, text)
    from public, anon, authenticated;
revoke all on function public.fail_trade_reflection(bigint, text)
    from public, anon, authenticated;
grant execute on function public.claim_trade_reflections(bigint, integer) to service_role;
grant execute on function public.complete_trade_reflection(bigint, text, text, text, text)
    to service_role;
grant execute on function public.fail_trade_reflection(bigint, text) to service_role;
