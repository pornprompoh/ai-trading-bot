create index if not exists dashboard_account_access_user_id_idx
    on public.dashboard_account_access (user_id);

create index if not exists dashboard_market_scans_account_idx
    on public.dashboard_market_scans (account_id, updated_at desc);

create unique index if not exists bot_commands_one_active_per_account_idx
    on public.bot_commands (account_id)
    where status in ('queued', 'processing');

