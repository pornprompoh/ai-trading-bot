create table if not exists public.trading_accounts (
    account_id bigint generated by default as identity primary key,
    login bigint not null,
    server varchar not null,
    account_type varchar not null,
    currency varchar not null,
    balance numeric not null,
    auto_trading boolean not null default false,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.trades (
    trade_id bigint generated by default as identity primary key,
    account_id bigint not null references public.trading_accounts(account_id),
    ticket bigint not null,
    symbol varchar not null,
    action varchar not null,
    volume numeric not null,
    open_price numeric not null,
    close_price numeric,
    sl_price numeric not null,
    tp_price numeric not null,
    open_time timestamptz not null,
    close_time timestamptz,
    profit_loss numeric,
    exit_reason varchar,
    created_at timestamptz not null default now(),
    status varchar not null
);

create table if not exists public.ai_trade_logs (
    log_id bigint generated by default as identity primary key,
    trade_id bigint not null references public.trades(trade_id) on delete cascade,
    symbol varchar not null,
    timeframe varchar not null,
    indicators_snapshot jsonb not null default '{}'::jsonb,
    ai_reasoning text not null,
    market_session varchar not null,
    created_at timestamptz not null default now()
);

create table if not exists public.account_equity_snapshots (
    id bigint generated by default as identity primary key,
    account_id bigint not null references public.trading_accounts(account_id) on delete cascade,
    balance numeric not null,
    equity numeric not null,
    margin numeric not null default 0,
    free_margin numeric not null default 0,
    recorded_at timestamptz not null default now()
);

create table if not exists public.dashboard_account_access (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    account_id bigint not null references public.trading_accounts(account_id) on delete cascade,
    created_at timestamptz not null default now()
);

create table if not exists public.dashboard_market_scans (
    scan_id bigint generated by default as identity primary key,
    account_id bigint not null references public.trading_accounts(account_id) on delete cascade,
    symbol varchar not null,
    timeframe varchar not null,
    last_price numeric,
    rsi numeric,
    ema_trend varchar not null,
    signal_status varchar not null,
    reason text not null,
    updated_at timestamptz not null default now(),
    constraint dashboard_market_scans_account_symbol_key unique (account_id, symbol)
);

create table if not exists public.bot_commands (
    command_id bigint generated by default as identity primary key,
    account_id bigint not null references public.trading_accounts(account_id) on delete cascade,
    requested_by uuid not null references auth.users(id),
    command_type varchar not null check (command_type = 'close_all'),
    status varchar not null default 'queued'
        check (status in ('queued', 'processing', 'completed', 'failed')),
    result text,
    created_at timestamptz not null default now(),
    processed_at timestamptz
);

create index if not exists trades_account_open_time_idx
    on public.trades (account_id, open_time desc);

create index if not exists trades_account_status_idx
