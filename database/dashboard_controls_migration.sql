-- Apply this migration to existing installations before deploying the engine.
alter table public.trading_accounts
    add column if not exists auto_trading boolean not null default false;

alter table public.account_equity_snapshots
    add column if not exists margin numeric not null default 0,
    add column if not exists free_margin numeric not null default 0;

create table if not exists public.dashboard_market_scans (
    scan_id bigint generated by default as identity primary key,
    account_id bigint not null references public.trading_accounts(account_id) on delete cascade,
    symbol varchar not null,
    timeframe varchar not null,
    last_price numeric,
    rsi numeric,
    ema_trend varchar not null,
    signal_status varchar not null,
    reason text not null,
    updated_at timestamptz not null default now(),
    constraint dashboard_market_scans_account_symbol_key unique (account_id, symbol)
);

create table if not exists public.bot_commands (
    command_id bigint generated by default as identity primary key,
    account_id bigint not null references public.trading_accounts(account_id) on delete cascade,
    requested_by uuid not null references auth.users(id),
    command_type varchar not null check (command_type = 'close_all'),
    status varchar not null default 'queued'
        check (status in ('queued', 'processing', 'completed', 'failed')),
    result text,
    created_at timestamptz not null default now(),
    processed_at timestamptz
);

create index if not exists dashboard_market_scans_account_idx
    on public.dashboard_market_scans (account_id, updated_at desc);

create unique index if not exists bot_commands_one_active_per_account_idx
    on public.bot_commands (account_id)
    where status in ('queued', 'processing');

alter table public.trading_accounts enable row level security;
alter table public.dashboard_market_scans enable row level security;
alter table public.bot_commands enable row level security;

drop policy if exists "Users can update assigned auto trading setting"
    on public.trading_accounts;
create policy "Users can update assigned auto trading setting"
    on public.trading_accounts for update to authenticated
    using (
        exists (
            select 1 from public.dashboard_account_access access
            where access.account_id = trading_accounts.account_id
              and access.user_id = (select auth.uid())
        )
        and lower(trading_accounts.account_type) = 'demo'
    )
    with check (
        exists (
            select 1 from public.dashboard_account_access access
            where access.account_id = trading_accounts.account_id
              and access.user_id = (select auth.uid())
        )
        and lower(trading_accounts.account_type) = 'demo'
    );

drop policy if exists "Users can read assigned market scans"
    on public.dashboard_market_scans;
create policy "Users can read assigned market scans"
    on public.dashboard_market_scans for select to authenticated
    using (
        exists (
            select 1 from public.dashboard_account_access access
            where access.account_id = dashboard_market_scans.account_id
              and access.user_id = (select auth.uid())
        )
    );

