create or replace function public.request_emergency_close_all(target_account_id bigint)
returns bigint
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
    new_command_id bigint;
begin
    if auth.uid() is null or not exists (
        select 1
        from public.dashboard_account_access access
        join public.trading_accounts account
          on account.account_id = access.account_id
        where access.account_id = target_account_id
          and access.user_id = auth.uid()
          and lower(account.account_type) = 'demo'
    ) then
        raise exception 'Not authorized for this trading account.';
    end if;

    perform pg_advisory_xact_lock(target_account_id);

    update public.trading_accounts
    set auto_trading = false
    where account_id = target_account_id;

    select command_id into new_command_id
    from public.bot_commands
    where account_id = target_account_id
      and status in ('queued', 'processing')
    order by created_at desc
    limit 1;

    if new_command_id is null then
        insert into public.bot_commands (account_id, requested_by, command_type)
        values (target_account_id, auth.uid(), 'close_all')
        returning command_id into new_command_id;
    end if;

    return new_command_id;
end;
$$;

revoke all on function public.request_emergency_close_all(bigint) from public;
revoke all on function public.request_emergency_close_all(bigint) from anon;
grant execute on function public.request_emergency_close_all(bigint) to authenticated;

create or replace view public.dashboard_risk_metrics
with (security_invoker = true)
as
with latest_snapshot as (
    select distinct on (account_id)
        account_id, equity, margin, free_margin, recorded_at
    from public.account_equity_snapshots
    order by account_id, recorded_at desc
),
daily_peaks as (
    select account_id, max(equity) as peak_equity
    from public.account_equity_snapshots
    where recorded_at >= date_trunc('day', now())
    group by account_id
),
all_time_peaks as (
    select account_id, max(equity) as max_equity_peak
    from public.account_equity_snapshots
    group by account_id
),
daily_trades as (
    select account_id, count(*)::bigint as daily_trade_count
    from public.trades
    where open_time >= date_trunc('day', now())
    group by account_id
)
select
    account.account_id,
    latest_snapshot.free_margin,
    case
        when latest_snapshot.margin > 0
        then latest_snapshot.equity / latest_snapshot.margin * 100
        else null
    end as margin_level,
    case
        when daily_peaks.peak_equity is null then null
        when daily_peaks.peak_equity > 0
        then (daily_peaks.peak_equity - latest_snapshot.equity)
            / daily_peaks.peak_equity * 100
        else 0
    end as daily_drawdown_percent,
    all_time_peaks.max_equity_peak,
    coalesce(daily_trades.daily_trade_count, 0) as daily_trade_count
from public.trading_accounts account
left join latest_snapshot on latest_snapshot.account_id = account.account_id
left join daily_peaks on daily_peaks.account_id = account.account_id
left join all_time_peaks on all_time_peaks.account_id = account.account_id
left join daily_trades on daily_trades.account_id = account.account_id;

grant select on public.dashboard_risk_metrics to authenticated;

create or replace view public.dashboard_symbol_exposure
with (security_invoker = true)
as
select
    account_id,
    symbol,
    count(*)::bigint as open_positions,
    coalesce(sum(volume), 0) as total_volume
from public.trades
where status = 'open'
group by account_id, symbol;

grant select on public.dashboard_symbol_exposure to authenticated;
